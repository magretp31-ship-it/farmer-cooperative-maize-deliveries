-- ICT371 QUESTION 9: FARMER COOPERATIVE MAIZE DELIVERIES
-- Grade A = K5/kg, B = K4/kg, C = K3/kg.

DROP VIEW IF EXISTS v_farmer_amount_due CASCADE;
DROP TABLE IF EXISTS daily_purchases, deliveries, farmers CASCADE;

CREATE TABLE farmers (
    farmer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_number VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL
);

CREATE TABLE deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INTEGER NOT NULL REFERENCES farmers(farmer_id),
    grade CHAR(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    weight_kg NUMERIC(12,2) NOT NULL CHECK (weight_kg > 0),
    unit_rate NUMERIC(8,2) NOT NULL CHECK (unit_rate > 0),
    total_value NUMERIC(14,2) NOT NULL CHECK (total_value >= 0),
    delivered_on DATE NOT NULL,
    is_paid BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE daily_purchases (
    purchase_date DATE PRIMARY KEY,
    total_weight NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_value NUMERIC(14,2) NOT NULL DEFAULT 0
);

-- (b) Return fixed grade rate.
CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade CHAR(1))
RETURNS NUMERIC(8,2) LANGUAGE plpgsql AS $$
BEGIN
    IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade cannot be NULL'; END IF;
    CASE UPPER(p_grade)
        WHEN 'A' THEN RETURN 5.00;
        WHEN 'B' THEN RETURN 4.00;
        WHEN 'C' THEN RETURN 3.00;
        ELSE RAISE EXCEPTION 'Unsupported maize grade: %', p_grade;
    END CASE;
END;
$$;

-- (d) Trigger calculates unit rate and total value for all inserts/updates.
CREATE OR REPLACE FUNCTION fn_set_delivery_value()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.weight_kg IS NULL OR NEW.weight_kg <= 0 THEN
        RAISE EXCEPTION 'Weight must be positive';
    END IF;
    NEW.unit_rate := fn_maize_rate(NEW.grade);
    NEW.total_value := ROUND(NEW.weight_kg * NEW.unit_rate, 2);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_delivery_pricing
BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION fn_set_delivery_value();

-- (c) Procedure leaves pricing to trigger.
CREATE OR REPLACE PROCEDURE pr_receive_delivery(
    p_farmer_id INTEGER, p_grade CHAR(1), p_weight NUMERIC, p_date DATE
)
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM farmers WHERE farmer_id = p_farmer_id) THEN
        RAISE EXCEPTION 'Unknown farmer ID: %', p_farmer_id;
    END IF;
    IF p_grade IS NULL OR UPPER(p_grade) NOT IN ('A', 'B', 'C') THEN
        RAISE EXCEPTION 'Grade must be A, B or C';
    END IF;
    IF p_weight IS NULL OR p_weight <= 0 OR p_date IS NULL THEN
        RAISE EXCEPTION 'Weight must be positive and delivery date is required';
    END IF;

    INSERT INTO deliveries(farmer_id, grade, weight_kg, unit_rate, total_value, delivered_on, is_paid)
    VALUES (p_farmer_id, UPPER(p_grade), p_weight, 1, 0, p_date, FALSE);
END;
$$;

